#!/usr/bin/env python3
"""Generate the portable subset from TZif files; requires IANA tzdata 2026e.

Run: python3 scripts/generate-tzdata.py /usr/share/zoneinfo
Use a directory built by zic from tzdata2026e on other platforms, with a
+VERSION file containing 2026e. Never consult the host clock during evaluation.
"""
import datetime as dt
import hashlib
import json
from pathlib import Path
import sys
from zoneinfo import ZoneInfo

root = Path(sys.argv[1])
assert (root / '+VERSION').read_text().strip() == '2026e'
zones = '''UTC Etc/UTC GMT Etc/GMT Z UT Europe/Paris Europe/Berlin Europe/Madrid Europe/Rome Europe/Amsterdam Europe/Brussels Europe/Vienna Europe/Stockholm Europe/Oslo Europe/Copenhagen Europe/Zurich Europe/London Europe/Lisbon Europe/Dublin Asia/Dhaka Asia/Kolkata Asia/Calcutta Asia/Karachi Asia/Tokyo Asia/Shanghai Asia/Hong_Kong Asia/Singapore America/New_York America/Toronto America/Chicago America/Los_Angeles America/Vancouver America/Mexico_City Australia/Sydney Australia/Melbourne Australia/Brisbane Australia/Perth Pacific/Auckland'''.split()
start = int(dt.datetime(1970, 1, 1, tzinfo=dt.timezone.utc).timestamp())
end = int(dt.datetime(2101, 1, 1, tzinfo=dt.timezone.utc).timestamp())
groups, hashes = {}, {}
for name in zones:
    path = root / (name if name not in ('Z', 'UT') else 'Etc/UTC')
    data = path.read_bytes()
    hashes[name] = hashlib.sha256(data).hexdigest()
    with path.open('rb') as handle:
        zone = ZoneInfo.from_file(handle)
    def offset(second):
        return int(dt.datetime.fromtimestamp(second, dt.timezone.utc).astimezone(zone).utcoffset().total_seconds())
    entries = [(start, offset(start))]
    at = start
    while at < end:
        nxt = min(at + 43200, end)
        if offset(nxt) != entries[-1][1]:
            lo, hi = at, nxt
            while hi - lo > 1:
                mid = (lo + hi) // 2
                if offset(mid) == entries[-1][1]:
                    lo = mid
                else:
                    hi = mid
            entries.append((hi, offset(hi)))
        at = nxt
    groups.setdefault(tuple(entries), []).append(name)
lines = ['// Generated by scripts/generate-tzdata.py; IANA tzdata 2026e, public domain.', '// UTC intervals [1970-01-01, 2101-01-01). Do not edit by hand.', '///|', 'fn zone_transitions(name : String) -> Array[(Int64, Int)]? {', '  match name {']
for entries, names in groups.items():
    lines.append('    ' + ' | '.join(json.dumps(n) for n in names) + ' => Some([')
    lines.extend(f'      ({second}L, {offset}),' for second, offset in entries)
    lines.append('    ])')
lines += ['    _ => None', '  }', '}']
Path('feel/types/tzdata_generated.mbt').write_text('\n'.join(lines) + '\n')
Path('scripts/tzdata-sources.json').write_text(json.dumps({'version':'2026e','zone_count':len(zones),'utc_start':start,'utc_end':end,'tzif_sha256':hashes},indent=2)+'\n')
print(f'{len(zones)} names; {len(groups)} unique transition tables')
