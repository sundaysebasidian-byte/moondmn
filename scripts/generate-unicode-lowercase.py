"""Generate locale-independent full lowercase tables from the vendored Unicode data."""
from pathlib import Path
import json

root = Path(__file__).resolve().parents[1]
mapping = {}
for line in (root/"scripts/UnicodeData-17.0.0.txt").read_text(encoding="utf-8").splitlines():
    fields = line.split(";")
    if fields[13]:
        mapping[int(fields[0], 16)] = [int(fields[13], 16)]
for line in (root/"scripts/SpecialCasing-17.0.0.txt").read_text(encoding="utf-8").splitlines():
    fields = line.partition("#")[0].split(";")
    if len(fields) >= 5 and not fields[4].strip():
        mapping[int(fields[0],16)] = [int(x,16) for x in fields[1].split()]

# Merge adjacent simple mappings with the same displacement.
ranges = []
expansions = []
for cp, lower in sorted(mapping.items()):
    if [cp] == lower:
        continue
    if len(lower) > 1:
        expansions.append((cp, "".join(map(chr, lower))))
        continue
    delta = lower[0] - cp
    if ranges and ranges[-1][1] + 1 == cp and ranges[-1][2] == delta:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp, delta])

lines = ["// Generated by scripts/generate-unicode-lowercase.py (Unicode 17.0.0).", "",
         "///|", "let lower_ranges : Array[(Int32, Int32, Int32)] = ["]
lines += [f"  ({lo}, {hi}, {d})," for lo, hi, d in ranges]
expansion_entries = [f"{cp}: {json.dumps(s, ensure_ascii=False)}" for cp, s in expansions]
lines += ["]", "", "///|"]
if len(expansion_entries) == 1:
    lines += [f"let lower_expansions : Map[Int32, String] = {{ {expansion_entries[0]} }}", ""]
else:
    lines += ["let lower_expansions : Map[Int32, String] = {"]
    lines += [f"  {entry}," for entry in expansion_entries]
    lines += ["}", ""]
(root/"feel/builtins/unicode_lower_data.mbt").write_text("\n".join(lines), encoding="utf-8", newline="\n")
