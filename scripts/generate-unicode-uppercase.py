"""Generate locale-independent full uppercase tables from the vendored Unicode data."""
from pathlib import Path
import json

root = Path(__file__).resolve().parents[1]
mapping = {}
for line in (root/"scripts/UnicodeData-17.0.0.txt").read_text().splitlines():
    fields = line.split(";")
    if fields[12]:
        mapping[int(fields[0], 16)] = [int(fields[12], 16)]
for line in (root/"scripts/SpecialCasing-17.0.0.txt").read_text().splitlines():
    fields = line.partition("#")[0].split(";")
    if len(fields) >= 5 and not fields[4].strip():
        mapping[int(fields[0],16)] = [int(x,16) for x in fields[3].split()]

# Merge adjacent simple mappings with the same displacement.
ranges = []
expansions = []
for cp, upper in sorted(mapping.items()):
    if [cp] == upper:
        continue
    if len(upper) > 1:
        expansions.append((cp, "".join(map(chr, upper))))
        continue
    delta = upper[0] - cp
    if ranges and ranges[-1][1] + 1 == cp and ranges[-1][2] == delta:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp, delta])

lines = ["// Generated by scripts/generate-unicode-uppercase.py (Unicode 17.0.0).", "",
         "///|", "let upper_ranges : Array[(Int32, Int32, Int32)] = ["]
lines += [f"  ({lo}, {hi}, {d})," for lo, hi, d in ranges]
lines += ["]", "", "///|", "let upper_expansions : Map[Int32, String] = {"]
lines += [f"  {cp}: {json.dumps(s, ensure_ascii=False)}," for cp, s in expansions]
lines += ["}", ""]
(root/"feel/builtins/unicode_upper_data.mbt").write_text("\n".join(lines))
