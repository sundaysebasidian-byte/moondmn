"""Generate Unicode 17 category sets used by XML Schema regex shorthands."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
sets = {"xpath_digits": [], "xpath_word_chars": []}
start = None
for line in (root / "scripts/UnicodeData-17.0.0.txt").read_text(encoding="utf-8").splitlines():
    value, name, category, *_ = line.split(";")
    cp = int(value, 16)
    if name.endswith(", First>"):
        assert start is None
        start = (cp, category)
        continue
    if name.endswith(", Last>"):
        assert start is not None and start[1] == category
        low = start[0]
        start = None
    else:
        assert start is None
        low = cp
    for key, match in (
        ("xpath_digits", category == "Nd"),
        ("xpath_word_chars", category[0] not in "PZC"),
    ):
        if not match:
            continue
        ranges = sets[key]
        if ranges and ranges[-1][1] + 1 == low:
            ranges[-1] = (ranges[-1][0], cp)
        else:
            ranges.append((low, cp))
assert start is None

out = ["// Generated by scripts/generate-xpath-categories.py (Unicode 17.0.0).", ""]
for key, ranges in sets.items():
    out.extend(["///|", f"let {key} : Array[(Int32, Int32)] = ["])
    out.extend(f"  ({lo}, {hi})," for lo, hi in ranges)
    out.extend(["]", ""])
(root / "feel/builtins/unicode_xpath_categories.mbt").write_text("\n".join(out), encoding="utf-8", newline="\n")
